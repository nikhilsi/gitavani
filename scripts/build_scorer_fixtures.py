#!/usr/bin/env python3
"""
Build scripts/data/scorer_fixtures.json: shared test cases for the Learn scorer.

The Python reference (scripts/chant_scorer.py) produces the expected answers. The Swift tests
(iOS) and the Kotlin tests (Android) load this file and must produce exactly the same answers.

Cases:
  sound_key:    text in, key out (IAST and the recognizer's Hindi-style Roman letters)
  deva_to_iast: Devanagari in, IAST out (Android's recognizer writes Devanagari)
  score:        a line (or joined verse) plus what was heard, with the expected marks and tip.
                Sources: the Nov 9 trial transcripts (reciter, altered recordings, Nikhil's takes)
                and synthetic takes with words removed, swapped or cut short.

Usage: python3 scripts/build_scorer_fixtures.py
"""

import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import chant_scorer as cs  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CHANT = os.path.join(ROOT, "data", "chant_data.json")
OUT = os.path.join(ROOT, "scripts", "data", "scorer_fixtures.json")

# What Apple's recognizer heard for verse 4.7 in the Nov 9 trial (docs/chant-coach-spec.md, section 15).
TRIAL_4_7 = {
    "reciter": "yada yadaahi dharmasya glaanirbhavathi Bharat abhyuthanama dharmasya tadatmanam shrajamyaham",
    "faster": "yada yadaahi dharmasya glaanirbhavathi Bharat abhyukthanama dharmasya tadatmanam shrajambyaham",
    "higher voice": "yada yadaahi dharmasya glaanirbhavati Bharat abhyut thana dharmasya tadat manam shrajam yaham",
    "room noise": "yada yadaahi dharmasya glaanirbhavati Bharat abhyuthanama dharmasya tadatmanam shrajamyaham",
    "wrong second line": "yada yadaahi dharmasya gla nirbhavati Bharat Maa karmaphala he turbu Maa te sangostvakarmani",
    "learner take 1": "Yada Yada hi Dharmasya claner bhavati Bharat, abhyutthanam, dharmasya, tadat, manam, samrajya, hum",
    "learner take 2": "yada yadaahi dharmasya glaner bhavati Bharat abhyukt Sam Sam Sam Sam tadat manam shramajyam",
    "learner take 3": "yada yadaahi dharmasya glaner bharata abhyutthanam dharmasya tadat manam smaraj",
    "stopped early": "yada yadaahi dharmasya glaanirbhavathi Bharat abhyuthanama",
    "nothing": "",
}


def case(name, line, heard, not_checked=()):
    result = cs.score_line(line, heard, not_checked)
    return {"name": name, "line": {"key": line["key"], "parts": [{"roman": p["roman"], "k": p["k"]} for p in line["parts"]]},
            "heard": heard, "not_checked": list(not_checked), "expected": result}


def main():
    verses = json.load(open(CHANT, encoding="utf-8"))["verses"]
    available = sorted(k for k, v in verses.items() if v["available"])
    rng = random.Random(9)

    score_cases = []
    whole_4_7 = cs.join_lines(verses["BG4.7"]["lines"])
    for name, heard in TRIAL_4_7.items():
        score_cases.append(case("4.7 " + name, whole_4_7, heard))
    score_cases.append(case("4.7 reciter with two parts not checked", whole_4_7, TRIAL_4_7["learner take 1"], (8, 10)))

    # Synthetic takes on random lines: clean, one word dropped, two words swapped, cut short, extra speech.
    for vid in rng.sample(available, 40):
        lines = [l for l in verses[vid]["lines"] if l["parts"]]
        line = rng.choice(lines)
        words = line["roman"].split()
        score_cases.append(case(vid + " clean", line, line["roman"]))
        if len(words) >= 3:
            k = rng.randrange(len(words))
            score_cases.append(case(vid + " drop word %d" % (k + 1), line, " ".join(words[:k] + words[k + 1:])))
            a = rng.randrange(len(words) - 1)
            swapped = words[:a] + [words[a + 1], words[a]] + words[a + 2:]
            score_cases.append(case(vid + " swap words %d and %d" % (a + 1, a + 2), line, " ".join(swapped)))
            score_cases.append(case(vid + " cut short", line, " ".join(words[: max(1, len(words) // 3)])))
        score_cases.append(case(vid + " extra speech", line, "um " + line["roman"] + " ok"))

    sample_lines = [l for vid in rng.sample(available, 25) for l in verses[vid]["lines"]]
    key_cases = [{"text": t, "key": cs.sound_key(t)} for t in
                 [l["roman"] for l in sample_lines] + list(TRIAL_4_7.values()) +
                 ["Krishna", "kshetre", "Xerox", "mafale", "sangostwakarmani", "geeta", "yoga", "Śrī Bhagavān"]]
    deva_cases = [{"deva": d, "iast": cs.deva_to_iast(d)} for d in
                  [l["deva"] for l in sample_lines] +
                  ["सङ्गोऽस्त्वकर्मणि", "ॐ", "पितॄन्", "श्रीभगवानुवाच", "क़ लम", "हं", "हः", "ऊवॉच", "ऑफ़ बॅट"]]

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"note": "Generated by scripts/build_scorer_fixtures.py from scripts/chant_scorer.py. Do not edit by hand.",
                   "constants": {"threshold": cs.THRESHOLD, "skip_share": cs.SKIP_SHARE,
                                 "unfinished_parts": cs.UNFINISHED_PARTS, "gap_open": cs.GAP_OPEN},
                   "sound_key": key_cases, "deva_to_iast": deva_cases, "score": score_cases},
                  f, ensure_ascii=False, indent=1)
    kinds = {}
    for c in score_cases:
        kinds[c["expected"]["tip"]["kind"]] = kinds.get(c["expected"]["tip"]["kind"], 0) + 1
    print("scorer_fixtures.json: %d sound_key, %d deva_to_iast, %d score cases; tips %s"
          % (len(key_cases), len(deva_cases), len(score_cases), kinds))


if __name__ == "__main__":
    main()
